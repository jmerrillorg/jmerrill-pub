    re.compile(r"^\s*Source artifact:\s*[0-9a-f-]{20,}\s*$", re.I),
    re.compile(r"^\s*Source checksum:\s*[0-9a-f]{32,}\s*$", re.I),
    re.compile(r"^\s*Correlation:\s*[A-Z0-9_:.-]+\s*$", re.I),
