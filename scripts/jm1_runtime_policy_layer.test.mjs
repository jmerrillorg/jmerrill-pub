test('author-facing artifact safety blocks internal metadata leakage', () => {
  assert.equal(policy.resolveArtifactAuthority({ text: 'Your Developmental Review is ready.' }).MUTATION_ALLOWED, true)
  for (const text of [
    'Generated by JMI Automation',
    'correlationId: abc',
    'checksum: deadbeef',
    'Dataverse workflow record',
    'AUTHOR_REVIEW_RESPONSE',
  ]) {
    assert.equal(policy.resolveArtifactAuthority({ text }).DECISION, 'DENY')
  }
})

test('superseded artifacts cannot become current production authority', () => {
  const denied = policy.resolveArtifactSupersessionAuthority({
    artifactId: 'proof-393',
    status: 'SUPERSEDED',
    supersededBy: 'proof-275',
  })
  assert.equal(denied.DECISION, 'DENY')
  assert.equal(denied.violationEvent, 'SUPERSEDED_ARTIFACT_AUTHORITY_VIOLATION')
})

test('editorial gates require upstream author approval and cadence eligibility', () => {
  assert.equal(policy.resolveEditorialStageAuthority({ stageCode: 'EDITORIAL_REVIEW' }).MUTATION_ALLOWED, true)
  assert.equal(policy.resolveEditorialStageAuthority({ stageCode: 'LINE_EDITING', priorAuthorGateCleared: false }).DECISION, 'DENY')
  assert.equal(policy.resolveEditorialStageAuthority({
    stageCode: 'LINE_EDITING',
    priorAuthorGateCleared: true,
    cadenceEligible: false,
    scheduledReleaseAt: '2026-08-26T02:01:42Z',
  }).DECISION, 'HUMAN_GATE')
})

test('publication intent prevents commissioning titles from requiring release metadata', () => {
  const commissioning = policy.resolvePublicationIntentAuthority({ publicationIntent: 'COMMISSIONING' })
  assert.equal(commissioning.MUTATION_ALLOWED, true)
  assert.equal(commissioning.isbnRequired, false)
  assert.equal(commissioning.distributionRequired, false)
  const commercial = policy.resolvePublicationIntentAuthority({ publicationIntent: 'COMMERCIAL_RELEASE' })
  assert.equal(commercial.isbnRequired, true)
})

test('production authority fails closed when full-wrap inputs are missing', () => {
  const denied = policy.resolveProductionAuthority({
    publicationIntent: 'COMMISSIONING',
    trimSize: '6 x 9',
    pageCount: 275,
    imprint: 'J Merrill Publishing',
    sourceAssets: [{ type: 'FRONT_COVER', location: 'sharepoint://front-cover' }],
  })
  assert.equal(denied.DECISION, 'DENY')
  assert.deepEqual(denied.missing, ['BACK_COVER_COPY'])
})

test('Block 05 production authority blocks entry, stale artifacts, and distribution submission', () => {
  const entry = policy.resolveBlock05ProductionAuthority({
    phase: 'ENTRY',
    productionReady: true,
    finalEditorialManuscriptId: 'artifact-1',
    finalEditorialChecksum: 'a'.repeat(64),
    editorialApprovalsComplete: true,
    styleSheetAvailable: true,
    productionNotesAvailable: true,
    activeTitleProject: true,
    formatEntitlementsResolved: true,
  })
  assert.equal(entry.DECISION, 'DENY')
  assert.equal(entry.missing.includes('FINAL_EDITORIAL_CERTIFIED'), true)

  const final = policy.resolveBlock05ProductionAuthority({
    phase: 'FINAL_CERTIFICATION',
    scopeLockComplete: true,
    requiredWorkstreamsCertified: true,
    requiredAuthorApprovalsComplete: true,
    technicalValidationsPass: true,
    finalArtifactsIdentified: true,
    checksumsVerified: true,
    publicationMetadataReady: true,
    accessibilitySatisfiedOrGoverned: true,
    crossFormatSynchronizationPass: true,
    handoffPackageComplete: true,
    attemptedActions: ['DISTRIBUTION_SUBMISSION'],
  })
  assert.equal(final.DECISION, 'DENY')
  assert.equal(final.missing.includes('BLOCK05_DISTRIBUTION_SUBMISSION_FORBIDDEN'), true)

  const allowed = policy.resolveBlock05ProductionAuthority({
    phase: 'FINAL_CERTIFICATION',
    scopeLockComplete: true,
    requiredWorkstreamsCertified: true,
    requiredAuthorApprovalsComplete: true,
    technicalValidationsPass: true,
    finalArtifactsIdentified: true,
    checksumsVerified: true,
    publicationMetadataReady: true,
    accessibilitySatisfiedOrGoverned: true,
    crossFormatSynchronizationPass: true,
    handoffPackageComplete: true,
  })
  assert.equal(allowed.MUTATION_ALLOWED, true)
  assert.equal(allowed.publicationAssetsReadyAllowed, true)
})

test('waiting-on authority denies author wait without a delivered current request', () => {
  assert.equal(policy.resolveWaitingOnAuthority({
    waitingOn: 'WAITING_ON_AUTHOR',
    currentAuthorRequestDelivered: false,
  }).DECISION, 'DENY')
  assert.equal(policy.resolveWaitingOnAuthority({
    waitingOn: 'WAITING_ON_AUTHOR',
    currentAuthorRequestDelivered: true,
    unconsumedAuthorResponsePresent: false,
  }).MUTATION_ALLOWED, true)
  assert.equal(policy.resolveWaitingOnAuthority({
    waitingOn: 'WAITING_ON_SYSTEM',
  }).DECISION, 'DENY')
})
