import assert from 'node:assert/strict'
import test from 'node:test'
import {
  createRequire,
} from 'node:module'

const require = createRequire(import.meta.url)
const policy = require('../azure-functions/diagnostic-ai-runner/src/policy/canonPolicyLayer.js')

test('policy registry exposes every required resolver with canonical decision shape', () => {
  const resolvers = new Set(policy.POLICY_REGISTRY.map((row) => row.resolver))
  for (const resolver of [
    'resolvePaymentAuthority',
    'resolveCommunicationAuthority',
    'resolveIdentityAuthority',
    'resolveArtifactAuthority',
    'resolveEditorialStageAuthority',
    'resolvePublicationIntentAuthority',
    'resolveProductionAuthority',
    'resolveBlock05ProductionAuthority',
    'resolveDistributionAuthority',
    'resolveCadenceAuthority',
    'resolveWaitingOnAuthority',
    'resolveLegacySystemAuthority',
  ]) {
    assert.equal(resolvers.has(resolver), true, `${resolver} missing from registry`)
  }
  const decision = policy.resolvePaymentAuthority({ processor: 'STRIPE' })
  for (const field of [
    'POLICY',
    'POLICY_VERSION',
    'DECISION',
    'AUTHORITY_SOURCE',
    'SOURCE_RECORD',
    'EVIDENCE',
    'REASON',
    'OVERRIDE_ALLOWED',
    'OVERRIDE_REQUIRED',
    'OVERRIDE_AUTHORITY',
    'LEGACY_ALLOWED',
    'MUTATION_ALLOWED',
  ]) {
    assert.equal(Object.hasOwn(decision, field), true, `${field} missing`)
  }
})

test('new Publishing payments allow Stripe and deny MoonClerk fallback', () => {
  assert.equal(policy.resolvePaymentAuthority({ processor: 'STRIPE', context: 'NEW_PUBLISHING_TRANSACTION' }).MUTATION_ALLOWED, true)
  const denied = policy.resolvePaymentAuthority({ processor: 'MoonClerk', context: 'NEW_PUBLISHING_TRANSACTION' })
  assert.equal(denied.DECISION, 'DENY')
  assert.equal(denied.MUTATION_ALLOWED, false)
  assert.equal(denied.violationEvent, 'PAYMENT_PROCESSOR_CANON_VIOLATION')
  const legacy = policy.resolvePaymentAuthority({ processor: 'MoonClerk', context: 'LEGACY_RECONCILIATION' })
  assert.equal(legacy.DECISION, 'LEGACY_RECONCILIATION_ONLY')
  assert.equal(legacy.LEGACY_ALLOWED, true)
})

test('communication authority requires ACS sender, Publishing reply-to, Publishing CC, and HTML', () => {
  const allowed = policy.resolveCommunicationAuthority({
    from: 'publishing@email.jmerrill.one',
    replyTo: 'publishing@jmerrill.one',
    to: ['author@example.com'],
    cc: ['publishing@jmerrill.one'],
    html: '<!doctype html><html><body>Good day.</body></html>',
  })
  assert.equal(allowed.MUTATION_ALLOWED, true)

  for (const input of [
    { from: 'noreply@email.jmerrill.one', replyTo: 'publishing@jmerrill.one', to: ['author@example.com'], cc: ['publishing@jmerrill.one'], html: '<!doctype html><html></html>' },
    { from: 'publishing@email.jmerrill.one', replyTo: 'noreply@email.jmerrill.one', to: ['author@example.com'], cc: ['publishing@jmerrill.one'], html: '<!doctype html><html></html>' },
    { from: 'publishing@email.jmerrill.one', replyTo: 'publishing@jmerrill.one', to: ['author@example.com'], cc: [], html: '<!doctype html><html></html>' },
    { from: 'publishing@email.jmerrill.one', replyTo: 'publishing@jmerrill.one', to: ['author@example.com'], cc: ['publishing@jmerrill.one'], text: 'plain only' },
  ]) {
    assert.equal(policy.resolveCommunicationAuthority(input).DECISION, 'DENY')
  }
})

