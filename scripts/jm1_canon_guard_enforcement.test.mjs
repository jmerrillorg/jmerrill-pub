for (const item of cases) {
  test(`${item.id} pass case allows governed action`, () => {
    assert.doesNotThrow(() => item.fn(item.pass))
  })

  test(`${item.id} fail case blocks and exposes execution-log event id`, () => {
    assert.throws(
      () => item.fn(item.fail),
      (error) => {
        assert.equal(error.guardId, item.id)
        assert.equal(error.executionLogEventId, `CANON_GUARD_FAILURE_${item.id}`)
        const failureLog = guard.canonGuardFailureLog({
          guardId: error.guardId,
          failureCode: error.failureCode,
          detail: error.message,
        })
        assert.equal(failureLog.actionType, `CANON_GUARD_FAILURE_${item.id}`)
        assert.match(failureLog.description, new RegExp(`Canon guard ${item.id} blocked execution`))
        return true
      },
    )
  })
}

