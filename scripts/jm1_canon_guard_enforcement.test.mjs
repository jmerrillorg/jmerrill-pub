test('prior incorrect later-chapters-recto rule cannot re-enter through Bootstrap', () => {
  assert.match(bootstrap, /subsequentChapters: 'NATURAL_FLOW'/)
  assert.doesNotMatch(bootstrap, /subsequentChapters: 'RECTO'/)
})

test('generated or historical evidence cannot override approved print canon in guard fixtures', () => {
  const unapprovedEvidenceRecord = {
    provenance: 'GENERATED_EVIDENCE',
    printProduction: {
      chapter1: 'RECTO',
      subsequentChapters: 'RECTO',
    },
  }
  const approvedCanon = {
    provenance: 'APPROVED_CANON',
    printProduction: {
      chapter1: 'RECTO',
      subsequentChapters: 'NATURAL_FLOW',
    },
  }

  assert.equal(unapprovedEvidenceRecord.provenance, 'GENERATED_EVIDENCE')
  assert.equal(approvedCanon.printProduction.subsequentChapters, 'NATURAL_FLOW')
  assert.notEqual(unapprovedEvidenceRecord.provenance, 'APPROVED_CANON')
})

