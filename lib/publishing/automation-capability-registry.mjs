export function summarizeAutomationCapabilities(registry = V1V2_AUTOMATION_CAPABILITY_REGISTRY) {
  const byStatus = countBy(registry, 'ProductionStatus')
  const byPriority = countBy(registry, 'Priority')
  const p0 = registry.filter((row) => row.Priority === 'P0')
  const p1 = registry.filter((row) => row.Priority === 'P1')
  const missingDisposition = registry.filter((row) => !COMPLETION_STATES.includes(row.ProductionStatus))
  const p0MissingMigration = p0.filter((row) => row.ProductionStatus === 'FOUNDER_DECISION_REQUIRED')
  const p1UnownedMissingMigration = p1.filter((row) => row.ProductionStatus === 'FOUNDER_DECISION_REQUIRED' && !row.Owner)
  const jackieAsEventBus = registry.some((row) =>
    /manual founder relay|manual status checking|manual mailbox monitoring|manual reply reading/i.test(row.SupersededV1Implementation || '') &&
    row.ProductionStatus === 'FOUNDER_DECISION_REQUIRED'
  )

  return {
    RegistryVersion: REGISTRY_VERSION,
    TotalCapabilities: registry.length,
    P0Capabilities: p0.length,
    P1Capabilities: p1.length,
    ProductionStatusCounts: byStatus,
    PriorityCounts: byPriority,
    UnknownCapabilityDispositions: missingDisposition.length,
    P0MissingMigrations: p0MissingMigration.length,
    P1UnownedMissingMigrations: p1UnownedMissingMigration.length,
    JackieAsEventBus: jackieAsEventBus ? 'YES' : 'NO',
    WholeFirstBreak: 'REPAIRED_TO_GOVERNED_ACTION_REQUEST_AND_REPLY_INGESTION',
  }
}

